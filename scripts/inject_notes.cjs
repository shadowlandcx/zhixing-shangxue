const reportsDir = path.join(__dirname, "..", "src", "data", "reports");
let done = 0;
const err = [];
for (const id of Object.keys(notes).sort()) {
  const f = path.join(reportsDir, id + ".js");
  if (!fs.existsSync(f)) { err.push(id + " 文件缺失"); continue; }
  const content = fs.readFileSync(f, "utf8");
  const idx = content.indexOf("## 五、读书会荐语");
  if (idx < 0) { err.push(id + " 无第五章"); continue; }
  const head = content.substring(0, idx).replace(/\s*$/, "");
  const meta = metaMap[id] || {};
  const reason = meta.reason ? String(meta.reason).replace(/\n+/g, " ").trim() : "";
  let ch5 = "\n\n## 五、读书会荐语\n\n";
  if (reason) {
    ch5 += "读书会原荐语如下：\n\n> " + reason + "\n\n";
  } else {
    ch5 += "读书会暂未留荐语。\n\n";
  }
  const note = notes[id];
  if (!note) { err.push(id + " 缺导读注"); continue; }
  ch5 += "**【知行商学导读】** " + note + "\n\n";
  const newContent = head + ch5 + "`;";
  const body = newContent.slice(newContent.indexOf("`") + 1, newContent.lastIndexOf("`"));
  if (body.includes("`") || body.includes("${")) {
    err.push(id + " 含非法字符(反引号/${)"); continue;
  }
  fs.writeFileSync(f, newContent);
  done++;
}
console.log("注入完成:", done, " 异常:", err.length);
if (err.length) console.log(err.join("\n"));
