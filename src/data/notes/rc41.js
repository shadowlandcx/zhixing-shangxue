  - 强调流程型组织的三个标志：客户导向、端到端拉通、持续改进；并提醒文化、IT、人才要同步配套，单点突破不够。
  - 给读者一个收尾判断：管理进步的尽头，是把经验变成流程、把流程变成系统、把系统变成能力，能力长在组织里而非人头里。
  - 作者最后呼吁：流程型组织不是大公司的专利，小团队同样可以从一条流程开始，先跑通再扩展。
