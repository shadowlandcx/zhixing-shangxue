里斯在这本书里把「聚焦」从一个建议变成了战略核心：在品类泛滥的时代，企业最大的风险不是做不够，而是做太多——产品线太宽、品牌太多、目标客户太散。书里那句「聚焦不是让你只做一件事，是让你只代表一个品类」，把聚焦从战术动作提升到了战略高度。

