export const note = `# 《可信赖顾问》读书笔记

> 为什么读：这本书是专业服务领域的「信任圣经」。梅斯特、格林、加弗德三位作者把「信任」从一个模糊的感觉拆成了可测量、可训练的公式。我在带政企销售团队的过程中发现，最顶尖的销售和普通销售的差距，不在于产品知识，不在于方案能力，而在于**客户是不是真的信任你**——不是信你的产品，是信你这个人。

## 为什么读

书里有一个核心公式，被称为「信任等式」：

**信任 = (可信度 + 可靠度 + 亲近度) / 自我导向**

分子越大，信任越大。分母越大，信任越小。这个公式看似简单，但每一个销售都可以在上面找到自己的问题。

| 要素 | 含义 | 销售怎么做 |
|------|------|-----------|
| **可信度** | 你说的是不是真的 | 不夸大产品能力、不承诺做不到的事 |
| **可靠度** | 你做的和你说的是不是一致 | 说了就做到，做不到提前说 |
| **亲近度** | 客户跟你在一起舒不舒服 | 不推销、不施压、让客户说真话 |
| **自我导向** | 你关心客户还是关心自己 | 每句话背后是「我要成单」还是「我要帮你」 |

**我的体会**：「自我导向」这个分母是我以前最不注意的。销售在客户面前最常见的动作——问预算、催方案、要承诺——全部在增加分母。客户感觉得到你在想「我什么时候能签单」，信任立刻打折。

## 核心框架

梅斯特把信任的建立拆成五个步骤，从「接触」到「承诺」：

| 步骤 | 核心动作 | 关键原则 |
|------|---------|---------|
| **第一步：客户委托** | 让客户愿意开口说真问题 | 不推销，先问「您现在最头疼的是什么？」 |
| **第二步：倾听** | 听懂客户没说出口的那句话 | 不打断、不急着回应、听完再开口 |
| **第三步：界定问题** | 和客户一起定义「什么才是真问题」 | 不要急着给方案，先确认问题 |
| **第四步：构想** | 一起想解决方案 | 让客户参与进来，不要自己做完扔给客户 |
| **第五步：承诺** | 明确下一步，谁在什么时候做什么 | 不说「再看看」，说「周三前我给您一个初版」 |

五个步骤中，**第二步和第三步是大多数销售跳过的**——他们听到客户说问题，立刻跳到第四步给方案。但梅斯特说：**跳过第二步和第三步，客户永远不会信任你——因为你根本不了解他的真问题。**

## 分章精读

### 第一章：什么是可信赖的顾问

梅斯特开篇就定义了「可信赖的顾问」——不是「产品知识最丰富的销售」，不是「价格最便宜的销售」，而是**客户在遇到问题时第一个想到的人**。

| 普通销售 | 可信赖的顾问 |
|---------|------------|
| 客户问什么答什么 | 客户还没问就猜到他要问什么 |
| 讲自己产品的功能 | 讲客户的问题怎么解决 |
| 急着证明自己 | 耐心帮客户想清楚 |
| 成交后消失 | 成交后还在为客户着想 |

**我的体会**：这个定义让我重新审视了自己的客户关系。我手上有几个合作了五年以上的客户——他们不是因为我产品最好才留下来的，是因为**他们遇到问题的时候第一个打电话给我**，哪怕这个问题跟我卖的产品没关系。这就是可信赖的顾问。

### 第二章：信任等式

这是全书最核心的一章。梅斯特把信任拆成四个要素，每个要素都可以测量和训练。

**可信度（Credibility）——你说的是不是真的**

| 高可信度 | 低可信度 |
|---------|---------|
| 「这个需求不在我们的核心能力范围内，做了也做不好」 | 「这个需求我们也可以做」 |
| 「标准交付 8 周，压缩到 6 周需要加钱加人」 | 「交付周期可能会稍微长一点」 |
| 「我们的方案在 XX 场景下效果是 XX」 | 「我们的方案适用于所有场景」 |

**可靠度（Reliability）——你做的和说的是不是一致**

| 高可靠度 | 低可靠度 |
|---------|---------|
| 说了周三给方案，周三一定给 | 说了周三给方案，周五还没发 |
| 客户问一个问题，当天回复 | 客户问一个问题，三天后才回 |
| 承诺的事一件不落 | 承诺的事十件落三件 |

**亲近度（Rapport）——客户跟你在一起舒不舒服**

| 高亲近度 | 低亲近度 |
|---------|---------|
| 客户说话你听完再开口 | 客户说话你打断 |
| 「我理解您的顾虑」 | 「您听我解释」 |
| 说「我不知道」 | 什么问题都说「我知道」 |

**自我导向（Self-Orientation）——你关心客户还是关心自己**

这是梅斯特最强调的一点。**自我导向是分母——它越大，信任越小。** 销售在客户面前的每一个动作都在告诉客户「我在想什么」：

| 低自我导向 | 高自我导向 |
|----------|----------|
| 「您觉得这个方案哪里不合适？」 | 「这个方案真的非常适合你们」 |
| 「我先了解一下您的情况」 | 「你们预算多少？」 |
| 「这个我不确定，我回去查一下」 | 「这个没问题，我们肯定能做」 |

**我的体会**：「自我导向」这个维度我以前完全没有意识。后来我开始刻意训练自己——每次见客户前，在纸上写下「今天的目标是让客户说真话，不是让我签单」。这个简单的动作让我的客户沟通质量上了一个台阶。

### 第三章：信任的五个步骤

梅斯特把信任关系的建立拆成五个步骤，每个步骤都有具体的动作和常见的错误。

**第一步：客户委托（Engage）**

核心是让客户愿意开口说真问题。梅斯特说，客户一开始说的往往不是真问题——他可能说「预算有限」，但真问题是「我怕换了供应商之后出事」。

| 错误的做法 | 正确的做法 |
|----------|----------|
| 客户一说问题就给方案 | 先问「您能多说一点吗？」 |
| 急着证明自己 | 先表示「我想先了解清楚」 |
| 问封闭式问题 | 问开放式问题 |

**我的体会**：这个步骤我练了半年才做到。以前客户说「预算有限」，我的第一反应是「那我帮您想办法」——这是急着给方案。现在我会说「预算卡在哪个环节？」——客户通常听到这个问题之后，才会说出真正的原因。

**第二步：倾听（Listen）**

梅斯特在这章给了一个非常简单的训练方法：**客户说完话，不要立刻回应，先在心里复述一遍客户的意思，确认理解正确了再开口。**

这个看似简单的动作，大多数销售都做不到。客户说 30 秒，销售等 3 秒就急着开口——这 3 秒里听到的东西，比之前 30 分钟听到的都多。

| 倾听的等级 | 表现 |
|----------|------|
| 第一层：假装在听 | 眼神在听，脑子在想怎么回应 |
| 第二层：礼貌地听 | 听完再回应，但回应的是自己的想法 |
| 第三层：同理心地听 | 听完、理解了、回应客户的情绪 |
| 第四层：全神贯注地听 | 听完、理解了、回应客户的真问题 |

**我的体会**：我以前基本在第一层和第二层之间。后来我用了一个土办法——**客户说话的时候，销售心里默数 3 秒再开口。** 一开始觉得尴尬，后来发现这 3 秒里听到的东西，比之前 30 分钟听到的都多。

**第三步：界定问题（Frame the Problem）**

梅斯特说，这一步是最容易被跳过的——销售听到客户说问题，立刻跳到「我有解决方案」。但梅斯特说：**如果你和客户对「什么才是真问题」的理解不一致，你的方案再好也不会被采纳。**

| 跳过这一步 | 认真做这一步 |
|----------|----------|
| 客户说「预算有限」，销售讲性价比 | 客户说「预算有限」，销售问「预算卡在哪？」 |
| 客户说「交付太慢」，销售讲加急方案 | 客户说「交付太慢」，销售问「哪个环节最慢？」 |
| 客户说「某某也在做」，销售攻击竞品 | 客户说「某某也在做」，销售问「您最看重他们哪一点？」 |

**我的体会**：这一步是整个信任建立过程中最重要的。我在团队里推行一个规则：**方案的第一页必须是「客户的问题定义」，不是「我们的解决方案」。** 如果客户对问题的定义和销售理解的不一致，方案后面的内容全错。

**第四步：构想（Envision）**

梅斯特在这章强调了一个容易被忽视的点：**解决方案不能由销售一个人做完扔给客户。** 客户必须参与构想的过程——否则客户不会把方案当成「自己的方案」。

| 销售一个人做 | 销售和客户一起做 |
|----------|----------|
| 销售做完方案发给客户 | 销售和客户一起过一遍，问「这里您觉得合适吗？」 |
| 方案里写「我们建议」 | 方案里写「我们的建议 + 您的反馈」 |
| 客户被动接受 | 客户主动参与修改 |

**我的体会**：这个原则在政企销售里尤其重要——政企客户的决策链条长，方案要经过很多轮评审。如果客户从头到尾没参与过方案的制定，评审的时候他会「找茬」。如果客户参与过，他会「帮腔」。

**第五步：承诺（Commit）**

梅斯特说，这一步的目标不是「签单」，是**给客户一个明确的、低压力的下一步**。

| 没做到 | 做到了 |
|--------|--------|
| 「您再考虑考虑」 | 「周三前我给您一个一页纸的总结」 |
| 「有什么问题随时联系我」 | 「下周三上午我给您打个电话，汇报一下进展」 |
| 客户不知道下一步 | 客户知道下一步是什么、什么时候、谁来做 |

**我的体会**：这一步是我以前最不注意的。每次见完客户，我说「有什么问题随时联系我」——这等于把主动权全给了客户。现在我会说「周三前我把方案发给您，您看可以吗？」——客户只需要说「可以」或「不行，改周五」。

### 第四章：信任的类型

梅斯特把信任分成三个层次，从低到高：

| 信任层次 | 含义 | 客户的表现 |
|---------|------|-----------|
| **交易型信任** | 信你的产品 | 「你们的产品确实不错」 |
| **关系型信任** | 信你这个人 | 「你这个人我信得过」 |
| **顾问型信任** | 信你的判断 | 「按你说的来」 |

大多数销售停留在第一层——客户信产品，但一旦有竞品出更低价格，客户就走了。只有到了第三层，客户才会说「按你说的来」——这时候价格就不重要了。

**我的体会**：这个框架让我明白了自己的客户结构。我手上有几个客户在第三层——他们说「按你说的来」，价格从来不是问题。但也有很多客户在第一层——他们信产品，但一旦有更好的选择就走了。我的目标是把第一层的客户往第二层、第三层推。

### 第五章：重建信任

梅斯特在这章讲了一个重要的点：**信任一旦失去，是可以重建的——但重建比建立难十倍。** 他给了一个重建信任的框架：

| 步骤 | 动作 |
|------|------|
| 1. 承认错误 | 不辩解、不推卸，「这是我的问题」 |
| 2. 说明影响 | 告诉客户这个问题造成了什么后果 |
| 3. 给出方案 | 「我已经做了什么、接下来做什么」 |
| 4. 请求反馈 | 「您看这样处理可以吗？」 |

**我的体会**：这个框架在政企销售里尤其重要。政企项目周期长、参与方多，出问题是大概率事件。客户最讨厌的不是出问题，是**出问题之后销售说「这不是我的问题」**。我现在要求团队：**出问题第一句话是「这是我的问题，我来解决」，不是「这不是我的问题」。**

## 一句话带走

**客户信你的产品，是交易；客户信你的判断，才是关系。信任不是你证明出来的，是客户自己感受到的。`