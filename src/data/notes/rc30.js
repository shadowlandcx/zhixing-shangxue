  - 讲可得性启发与情感如何影响风险评估：易想起的被高估，平静发生的被低估，媒体曝光度绑架了概率感。
  - 揭示典型性如何压倒统计、回归均值常被误读为报复或因果，以及驯服直觉性预测的方法，用外部基准修正直觉。
  - 指出原因胜过统计让我们忽略基础概率，爱上连贯的故事而非可靠的频率；并补充模拟性启发，能轻易想象的结果显得更可能。
  - 论证有效性错觉在此显形：人们高估自己对过去的解释力，于是高估对未来的预测力；专家自信常与其准确率脱钩。
  - 补充少即是多的另一面：信息越多、故事越顺，人越自信，却未必越准，流畅感伪装成准确率。
