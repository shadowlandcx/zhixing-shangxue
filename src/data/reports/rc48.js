全书第三部分收录了管理者与思科高层的即兴问答，涉及人才、战略、创新等最接地气的问题。这种「带着真问题问、拿到真经验答」的结构，本身就是一种学习方法的示范：标杆学习不是听宣讲，而是拿自己的难题去碰撞对方的解法。对团队学习而言，这种「以问题为起点」的姿态，比任何标准答案都珍贵。

