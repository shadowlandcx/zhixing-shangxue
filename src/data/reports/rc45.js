工具选型优先级：如果团队现在最痛的是两难决策总拍脑袋，先上灰度决策两端风险工作纸加灰度思考训练卡；如果痛的是一线等指示、后方瞎指挥，先上分层分级授权边界清单加一线呼叫后方支撑责任图；如果痛的是顺境时没有预案，先上危机哲学四步推演加至暗时刻应对清单；如果痛的是交付质量飘忽，先上磨好豆腐交付红线加悲悯式客户拜访话术。先治最痛的那道墙，别二十二件一起铺，一起铺等于都没铺。

