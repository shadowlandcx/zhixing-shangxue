危机哲学我每季度带团队做一次推演：列最大三风险，对每风险写若发生靠什么活，定一个今天就能做的小预案，责任到人设复查点。顺境时做这件事实在反直觉，但真到事上，肌肉记忆比临时慌乱管用。

带头人自我剖白是我最受益的一条。每月复盘会我先讲自己本周期做错的一件事与教训，再请大家补充。示弱反而建立真实信任，也示范了灰度不是护短，而是坦然面对不完美。注意剖白要具体，不能泛泛说我有不足，否则变成表演。

团队视角最后一句：带团队管灰度，最难的是自己先扛住不完美。很多主管嘴上讲灰度，底下人一出错就炸，团队自然不敢试错。我自己的经验是，先把自我剖白做成固定仪式，团队才敢把真实问题摊开。灰度是长出来的信任，不是下令就能有的。

