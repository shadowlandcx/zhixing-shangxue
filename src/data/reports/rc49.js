第二类是从关系驱动走向体系驱动的断层。很多企业营销停留在老板关系、销售个人英雄、零散获客，关键人一走，增长立刻失速。本书主张把营销从战术支持升级为战略引领，用一套体系把市场、产品、销售、交付、客户成功拧成一股绳。我带过一个靠老板个人关系撑起来的团队，老板一淡出，单子立刻断供，那才叫真正的风险。

