（1）底层认知：变革是为了什么
作者先立住根基。企业存在的唯一理由是为客户创造价值；企业竞争的本质是管理的竞争；管理第一、技术第二；管理进步依赖于持续有效的变革。这一节是在给变革正名，变革不是折腾，是组织活下去的基础，是应对不确定性的唯一答案。我当年迷信过一次新系统，以为上了系统业绩自然涨，结果流程没理顺，工具反而成负担，就是典型的为技术而技术。

