怀斯曼和麦吉沃恩这本书的核心命题非常吸引人——**有的领导者让员工的才智翻倍，有的领导者让员工的才智减半。** 他们把前者叫「乘法领导者」，后者叫「除法领导者」。这篇研报从销售、营销、团队三个视角拆解这本书在政企行业的实战用法。


