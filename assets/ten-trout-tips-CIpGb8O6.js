《特劳特营销十要》解决的核心问题是：**你的营销动作是否违反了某条基本原则？** 大多数营销失败不是「不够努力」，是「从第一条就错了」——定位不清晰、差异化不明确、试图满足所有人、在领导者优势位置硬碰、品牌延伸稀释、打价格战、忽视竞争、创新稀释定位、忽视渠道、停止传播。

