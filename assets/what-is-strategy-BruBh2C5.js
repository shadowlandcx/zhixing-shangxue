4. **定位传播模板**：「一个词 + 一个画面 + 一个案例」——确保定位传播聚焦。
5. **运营活动环环相扣检查表**：逐条检查每个运营活动是否在支撑同一个定位，找到断裂点。
6. **战术陷阱排查表**：对照「更好产品」「满足所有人」「技术领先」「短期利润」四类陷阱，排查当前决策是否踩坑。
7. **战略自检工具**：每年一次，回答「我们代表什么」——如果答案变了，战略就要调整。
8. **切入点筛选工具**：从「友商弱势」「客户在意」「我们能赢」三个条件筛选战术切入点，三个条件缺一不可。

