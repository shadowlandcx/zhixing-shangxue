董事会战略决策的五个维度：

1. **品类选择**：我们在哪个品类中竞争？这个品类有前景吗？
2. **定位选择**：我们在品类中代表什么？是第一吗？
3. **品牌打造**：品牌是否代表品类？还是只是一个商标？
