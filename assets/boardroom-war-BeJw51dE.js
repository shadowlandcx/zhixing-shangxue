董事会是企业战略决策的最高战场，而里斯在这本书里指出：董事会里最常见的失败不是「战略选错了」，而是「没有战略」——大家在讨论产品、价格、渠道，却没人问「我们代表什么品类」。这本书把董事会战略决策拆成三个问题：品类是否清晰、定位是否明确、品牌是否代表品类。

