我刚带队伍那阵子，最大的痛苦是道理都懂、落地就歪。这本书我前后翻过几遍，每次都能从里面捞出一条能直接用在我自己团队上的动作。我把这些动作连同我踩过的坑一起记在下面。

> 过去企业是「向销售要收入」，现在不得不「向采购要利润」，当产能过剩、利润变薄，客户的采购部门从后台走向台前，成了决定你订单命运的守门人。
